// Builds dist/basemap.mjs (projected SVG paths for the contiguous US) and the FIT constants in dist/geo.mjs.
// Dev-only. Run from a directory that has the source packages installed:
//   npm i us-atlas@3.0.1 topojson-client@3.1.0 topojson-simplify@3.0.3
//   node /path/to/AeroCommit/tools/build-basemap.mjs
// Boundary data: US Census Bureau cartographic boundaries via us-atlas (ISC license).
import {createRequire} from 'node:module';
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname, join} from 'node:path';

const require = createRequire(join(process.cwd(), '/'));
const topojson = require('topojson-client');
const simplify = require('topojson-simplify');
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const geoPath = join(root, 'dist/geo.mjs');
const {albers} = await import(geoPath);

const VIEW = {w: 850, h: 420, left: 40, right: 810, top: 20, bottom: 372};
const EXCLUDE = new Set(['02', '15', '60', '66', '69', '72', '78']); // Alaska, Hawaii and territories

let topo = JSON.parse(readFileSync(require.resolve('us-atlas/states-10m.json'), 'utf8'));
topo = simplify.presimplify(topo);
topo = simplify.simplify(topo, simplify.quantile(topo, 0.12));
const lower48 = {type: 'GeometryCollection', geometries: topo.objects.states.geometries.filter(g => !EXCLUDE.has(g.id))};
const land = topojson.merge(topo, lower48.geometries);
const borders = topojson.mesh(topo, lower48, (a, b) => a !== b);

// Fit the land bounds into the drawing box, preserving aspect ratio.
let x0 = Infinity, x1 = -Infinity, y0 = Infinity, y1 = -Infinity;
for (const poly of land.coordinates) for (const ring of poly) for (const [lon, lat] of ring) {
  const [x, y] = albers(lon, lat); x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y);
}
const k = Math.min((VIEW.right - VIEW.left) / (x1 - x0), (VIEW.bottom - VIEW.top) / (y1 - y0));
const fit = {k, x: (VIEW.left + VIEW.right) / 2 - k * (x0 + x1) / 2, y: (VIEW.top + VIEW.bottom) / 2 + k * (y0 + y1) / 2};
const r4 = v => Math.round(v * 1e4) / 1e4;
const src = readFileSync(geoPath, 'utf8').replace(/export const FIT = \{[^}]*\};/, `export const FIT = {k: ${r4(fit.k)}, x: ${r4(fit.x)}, y: ${r4(fit.y)}};`);
writeFileSync(geoPath, src);

const proj = (lon, lat) => { const [x, y] = albers(lon, lat); return [r4(fit.x + fit.k * x), r4(fit.y - fit.k * y)]; };
const r1 = v => Math.round(v * 10) / 10;
function line(coords, close) {
  let d = '', last = '';
  coords.forEach(([lon, lat], i) => {
    const [x, y] = proj(lon, lat), p = `${r1(x)},${r1(y)}`;
    if (p === last) return;
    d += (d ? 'L' : 'M') + p; last = p;
  });
  return close ? d + 'Z' : d;
}
const landPath = land.coordinates.map(poly => poly.map(ring => line(ring, true)).join('')).join('');
const borderPath = borders.coordinates.map(l => line(l, false)).join('');
const grat = [];
for (let lon = -125; lon <= -65; lon += 5) grat.push(line(Array.from({length: 31}, (_, i) => [lon, 22 + i]), false));
for (let lat = 25; lat <= 50; lat += 5) grat.push(line(Array.from({length: 66}, (_, i) => [-127 + i, lat]), false));
const out = `// Generated by tools/build-basemap.mjs. Do not edit by hand.
// Contiguous US land and state borders, projected with geo.mjs (Albers equal-area) into the 850 × 420 map viewBox.
// Source: US Census Bureau cartographic boundaries (1:10m) via us-atlas 3.0.1, simplified.
export const LAND=${JSON.stringify(landPath)};
export const BORDERS=${JSON.stringify(borderPath)};
export const GRATICULE=${JSON.stringify(grat.join(''))};
`;
writeFileSync(join(root, 'dist/basemap.mjs'), out);
console.log('basemap.mjs', out.length, 'bytes; fit', fit);
