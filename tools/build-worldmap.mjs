// Builds dist/worldmap.mjs: North Atlantic land and country borders as compact lon/lat rings,
// projected at runtime by geo.mjs fitNetwork() for scenarios that include European airports.
// Dev-only. Run from a directory that has the source packages installed:
//   npm i world-atlas@2.0.2 topojson-client@3.1.0 topojson-simplify@3.0.3
//   node /path/to/AeroCommit/tools/build-worldmap.mjs
// Boundary data: Natural Earth 1:50m (public domain) via world-atlas (ISC license).
import {createRequire} from 'node:module';
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname, join} from 'node:path';

const require = createRequire(join(process.cwd(), '/'));
const topojson = require('topojson-client');
const simplify = require('topojson-simplify');
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// Region covering the contiguous US, Canada, the North Atlantic, Europe, Türkiye and North Africa.
const BOX = {west: -170, east: 60, south: 10, north: 75};
// Coordinates stored as integer hundredths of a degree; precision is ~1 km, far finer than the map draws.
const Q = 100;

let topo = JSON.parse(readFileSync(require.resolve('world-atlas/countries-50m.json'), 'utf8'));
topo = simplify.presimplify(topo);
topo = simplify.simplify(topo, simplify.quantile(topo, 0.08));
const countries = topo.objects.countries;
const land = topojson.merge(topo, countries.geometries);
const borders = topojson.mesh(topo, countries, (a, b) => a !== b);

// Afro-Eurasia touches the 180° meridian (Chukotka); unwrap far-eastern points so the ring stays continuous.
// Unwrapped points land east of 180°, off the drawn region, and are clipped by the map.
const unwrap = pts => {
  const lons = pts.map(p => p[0]);
  return Math.max(...lons) - Math.min(...lons) > 300 ? pts.map(([lon, lat]) => [lon < -150 ? lon + 360 : lon, lat]) : pts;
};
const inBox = pts => {
  let w = Infinity, e = -Infinity, s = Infinity, n = -Infinity;
  for (const [lon, lat] of pts) { w = Math.min(w, lon); e = Math.max(e, lon); s = Math.min(s, lat); n = Math.max(n, lat); }
  return e >= BOX.west && w <= BOX.east && n >= BOX.south && s <= BOX.north;
};
// Drop consecutive duplicates after quantizing; keep only rings and lines that touch the region.
function pack(pts, minPts) {
  const out = []; let lx = null, ly = null;
  for (const [lon, lat] of pts) {
    const x = Math.round(lon * Q), y = Math.round(lat * Q);
    if (x === lx && y === ly) continue;
    out.push(x, y); lx = x; ly = y;
  }
  return out.length / 2 >= minPts ? out : null;
}
// Skip islands smaller than ~0.15 square degrees (invisible at overview scale).
const area = r => Math.abs(r.reduce((s, [x, y], i) => { const [x2, y2] = r[(i + 1) % r.length]; return s + x * y2 - x2 * y; }, 0) / 2);
// Clip a closed ring to lon <= limit (Sutherland–Hodgman against one half-plane) so Asia doesn't ship.
const clipEast = (ring, limit = BOX.east + 15) => {
  const out = [];
  for (let i = 0; i < ring.length; i++) {
    const a = ring[i], b = ring[(i + 1) % ring.length], ina = a[0] <= limit, inb = b[0] <= limit;
    if (ina) out.push(a);
    if (ina !== inb) { const t = (limit - a[0]) / (b[0] - a[0]); out.push([limit, a[1] + t * (b[1] - a[1])]); }
  }
  return out;
};
const LAND = land.coordinates.flatMap(poly => poly).map(unwrap).map(r => clipEast(r)).filter(r => r.length >= 4).filter(r => inBox(r) && area(r) > 0.15).map(r => pack(r, 4)).filter(Boolean);
const BORDERS = borders.coordinates.map(unwrap).filter(l => l.some(([lon]) => lon <= BOX.east + 15)).filter(inBox).map(l => pack(l, 2)).filter(Boolean);

const out = `// Generated by tools/build-worldmap.mjs. Do not edit by hand.
// North Atlantic land and country borders, lon/lat in hundredths of a degree as flat [lon,lat,lon,lat,...] arrays.
// Source: Natural Earth 1:50m (public domain) via world-atlas 2.0.2, simplified. Region ${BOX.west}..${BOX.east}°E, ${BOX.south}..${BOX.north}°N.
export const SCALE=${Q};
export const WORLD_LAND=${JSON.stringify(LAND)};
export const WORLD_BORDERS=${JSON.stringify(BORDERS)};
`;
writeFileSync(join(root, 'dist/worldmap.mjs'), out);
console.log('worldmap.mjs', out.length, 'bytes;', LAND.length, 'land rings,', BORDERS.length, 'border lines');
