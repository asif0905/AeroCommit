// Builds proxy/cloudflare-worker.js as one self-contained file (the Cloudflare dashboard editor
// takes a single file) from tools/worker-template.js and relay.mjs. Run: node tools/build-worker.mjs
import {readFileSync, writeFileSync} from 'node:fs';
const root = new URL('../', import.meta.url);
export function buildWorker() {
  const relay = readFileSync(new URL('relay.mjs', root), 'utf8').replace(/^export /gm, '');
  const tpl = readFileSync(new URL('tools/worker-template.js', root), 'utf8');
  return '// Generated by tools/build-worker.mjs from relay.mjs. Edit those files, not this one.\n' + tpl.replace('/*RELAY*/\n', relay + '\n');
}
if (process.argv[1] && new URL(import.meta.url).pathname === process.argv[1]) writeFileSync(new URL('proxy/cloudflare-worker.js', root), buildWorker());
